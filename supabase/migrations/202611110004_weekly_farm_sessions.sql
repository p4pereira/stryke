-- Keeps every previous addition intact while grouping new farm entries into named weeks.
create table if not exists public.stryke_farm_weeks (
  id uuid primary key default gen_random_uuid(),
  week_number integer generated by default as identity unique,
  started_at timestamptz not null default now(),
  closed_at timestamptz
);
create unique index if not exists stryke_farm_weeks_one_active_idx
  on public.stryke_farm_weeks ((closed_at is null))
  where closed_at is null;
alter table public.stryke_farm_weeks enable row level security;
grant select, insert on public.stryke_farm_weeks to anon, authenticated;
grant update (closed_at) on public.stryke_farm_weeks to anon, authenticated;

alter table public.stryke_component_additions
  add column if not exists week_id uuid references public.stryke_farm_weeks(id) on delete restrict;
create index if not exists stryke_component_additions_week_id_idx
  on public.stryke_component_additions(week_id);

do $policies$
begin
  if not exists (select 1 from pg_policies where schemaname='public' and tablename='stryke_farm_weeks' and policyname='Public can read farm weeks') then
    execute 'create policy "Public can read farm weeks" on public.stryke_farm_weeks for select to anon, authenticated using (true)';
  end if;
  if not exists (select 1 from pg_policies where schemaname='public' and tablename='stryke_farm_weeks' and policyname='Public can open farm weeks') then
    execute 'create policy "Public can open farm weeks" on public.stryke_farm_weeks for insert to anon, authenticated with check (closed_at is null)';
  end if;
  if not exists (select 1 from pg_policies where schemaname='public' and tablename='stryke_farm_weeks' and policyname='Public can close active farm weeks') then
    execute 'create policy "Public can close active farm weeks" on public.stryke_farm_weeks for update to anon, authenticated using (closed_at is null) with check (closed_at is not null)';
  end if;
end
$policies$;

insert into public.stryke_farm_weeks (started_at)
select now()
where not exists (select 1 from public.stryke_farm_weeks where closed_at is null);

create or replace function public.stryke_open_new_week()
returns uuid
language plpgsql
security invoker
set search_path = pg_catalog, public
as $function$
declare
  active_week_id uuid;
  new_week_id uuid;
begin
  perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtextextended('stryke_open_new_week', 0));
  select id into active_week_id
  from public.stryke_farm_weeks
  where closed_at is null
  order by week_number desc
  limit 1
  for update;

  if active_week_id is not null then
    update public.stryke_farm_weeks
    set closed_at = now()
    where id = active_week_id;
  end if;

  insert into public.stryke_farm_weeks default values
  returning id into new_week_id;
  return new_week_id;
end;
$function$;

revoke all on function public.stryke_open_new_week() from public;
grant execute on function public.stryke_open_new_week() to anon, authenticated;
